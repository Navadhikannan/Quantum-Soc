`timescale 1ns/1ps
module if_id_tb;

parameter XLEN = 32;

//============================================================
// Inputs
//============================================================

reg clk;
reg reset;
reg write_enable;

reg [XLEN-1:0] pc_in;
reg [31:0] instruction_in;

//============================================================
// Outputs
//============================================================

wire [XLEN-1:0] pc_out;
wire [31:0] instruction_out;

//============================================================
// DUT
//============================================================

if_id #(
    .XLEN(XLEN)
) dut (
    .clk(clk),
    .reset(reset),
    .write_enable(write_enable),

    .pc_in(pc_in),
    .instruction_in(instruction_in),

    .pc_out(pc_out),
    .instruction_out(instruction_out)
);

//============================================================
// Clock Generation
//============================================================

initial begin
    clk = 0;
    forever #5 clk = ~clk;
end

//============================================================
// Test Sequence
//============================================================

initial begin

    $dumpfile("if_id.vcd");
    $dumpvars(0, if_id_tb);

    //--------------------------------------------------------
    // Test 1 : Reset
    //--------------------------------------------------------

    reset = 1;
    write_enable = 0;
    pc_in = 0;
    instruction_in = 0;

    #10;

    //--------------------------------------------------------
    // Test 2 : First Write
    //--------------------------------------------------------

    reset = 0;
    write_enable = 1;

    pc_in = 32'h00000004;
    instruction_in = 32'h00500093;

    #10;

    //--------------------------------------------------------
    // Test 3 : Pipeline Stall
    //--------------------------------------------------------

    write_enable = 0;

    pc_in = 32'h00000008;
    instruction_in = 32'h00800113;

    #10;

    //--------------------------------------------------------
    // Test 4 : Second Write
    //--------------------------------------------------------

    write_enable = 1;

    pc_in = 32'h00000008;
    instruction_in = 32'h00800113;

    #10;

    //--------------------------------------------------------
    // Test 5 : Third Write
    //--------------------------------------------------------

    pc_in = 32'h0000000C;
    instruction_in = 32'h002081B3;

    #10;

    $finish;

end

endmodule