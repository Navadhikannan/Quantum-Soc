`timescale 1ns/1ps

module control_unit_tb;

//==========================================================
// Inputs
//==========================================================

reg [6:0] opcode;

//==========================================================
// Outputs
//==========================================================

wire reg_write;
wire alu_src;
wire mem_read;
wire mem_write;
wire mem_to_reg;
wire branch;
wire jump;
wire [1:0] alu_op;

//==========================================================
// DUT
//==========================================================

control_unit dut (

    .opcode(opcode),

    .reg_write(reg_write),
    .alu_src(alu_src),
    .mem_read(mem_read),
    .mem_write(mem_write),
    .mem_to_reg(mem_to_reg),
    .branch(branch),
    .jump(jump),
    .alu_op(alu_op)

);

//==========================================================
// Test Sequence
//==========================================================

initial begin

    $dumpfile("control_unit.vcd");
    $dumpvars(0, control_unit_tb);

    //------------------------------------------------------
    // R-Type
    //------------------------------------------------------

    opcode = 7'b0110011;
    #10;

    //------------------------------------------------------
    // I-Type
    //------------------------------------------------------

    opcode = 7'b0010011;
    #10;

    //------------------------------------------------------
    // LOAD
    //------------------------------------------------------

    opcode = 7'b0000011;
    #10;

    //------------------------------------------------------
    // STORE
    //------------------------------------------------------

    opcode = 7'b0100011;
    #10;

    //------------------------------------------------------
    // BRANCH
    //------------------------------------------------------

    opcode = 7'b1100011;
    #10;

    //------------------------------------------------------
    // JAL
    //------------------------------------------------------

    opcode = 7'b1101111;
    #10;

    //------------------------------------------------------
    // JALR
    //------------------------------------------------------

    opcode = 7'b1100111;
    #10;

    //------------------------------------------------------
    // LUI
    //------------------------------------------------------

    opcode = 7'b0110111;
    #10;

    //------------------------------------------------------
    // AUIPC
    //------------------------------------------------------

    opcode = 7'b0010111;
    #10;

    //------------------------------------------------------
    // Invalid Opcode
    //------------------------------------------------------

    opcode = 7'b1111111;
    #10;

    $finish;

end

//==========================================================
// Monitor
//==========================================================

initial begin

$monitor(
"Time=%0t | Opcode=%b | RegWrite=%b | ALUSrc=%b | MemRead=%b | MemWrite=%b | MemToReg=%b | Branch=%b | Jump=%b | ALUOp=%b",
    $time,
    opcode,
    reg_write,
    alu_src,
    mem_read,
    mem_write,
    mem_to_reg,
    branch,
    jump,
    alu_op
);

end

endmodule