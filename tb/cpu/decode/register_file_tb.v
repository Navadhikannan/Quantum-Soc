`timescale 1ns/1ps

module register_file_tb;

parameter XLEN = 32;
parameter REG_COUNT = 32;

//==========================================================
// Inputs
//==========================================================

reg clk;
reg reset;

reg [4:0] rs1;
reg [4:0] rs2;

reg reg_write;
reg [4:0] rd;
reg [XLEN-1:0] write_data;

//==========================================================
// Outputs
//==========================================================

wire [XLEN-1:0] read_data1;
wire [XLEN-1:0] read_data2;

//==========================================================
// DUT
//==========================================================

register_file #(
    .XLEN(XLEN),
    .REG_COUNT(REG_COUNT)
) dut (

    .clk(clk),
    .reset(reset),

    .rs1(rs1),
    .rs2(rs2),

    .read_data1(read_data1),
    .read_data2(read_data2),

    .reg_write(reg_write),
    .rd(rd),
    .write_data(write_data)

);

//==========================================================
// Clock Generation
//==========================================================

initial begin
    clk = 0;
    forever #5 clk = ~clk;
end

//==========================================================
// Test Sequence
//==========================================================

initial begin

    $dumpfile("register_file.vcd");
    $dumpvars(0, register_file_tb);

    //------------------------------------------------------
    // Initialize
    //------------------------------------------------------

    reset      = 1;
    reg_write  = 0;
    rs1        = 0;
    rs2        = 0;
    rd         = 0;
    write_data = 0;

    #12;

    //------------------------------------------------------
    // Release Reset
    //------------------------------------------------------

    reset = 0;

    //------------------------------------------------------
    // Write x5 = 100
    //------------------------------------------------------

    reg_write  = 1;
    rd         = 5;
    write_data = 32'd100;

    #10;

    //------------------------------------------------------
    // Read x5
    //------------------------------------------------------

    reg_write = 0;

    rs1 = 5;
    rs2 = 0;

    #10;

    //------------------------------------------------------
    // Write x10 = 200
    //------------------------------------------------------

    reg_write  = 1;
    rd         = 10;
    write_data = 32'd200;

    #10;

    //------------------------------------------------------
    // Read x10
    //------------------------------------------------------

    reg_write = 0;

    rs1 = 10;
    rs2 = 0;

    #10;

    //------------------------------------------------------
    // Simultaneous Read
    //------------------------------------------------------

    rs1 = 5;
    rs2 = 10;

    #10;

    //------------------------------------------------------
    // Try Writing x0 (Should Fail)
    //------------------------------------------------------

    reg_write  = 1;
    rd         = 0;
    write_data = 32'd999;

    #10;

    //------------------------------------------------------
    // Read x0
    //------------------------------------------------------

    reg_write = 0;

    rs1 = 0;
    rs2 = 5;

    #10;

    //------------------------------------------------------
    // Write x15 = 500
    //------------------------------------------------------

    reg_write  = 1;
    rd         = 15;
    write_data = 32'd500;

    #10;

    //------------------------------------------------------
    // Read x15
    //------------------------------------------------------

    reg_write = 0;

    rs1 = 15;
    rs2 = 10;

    #10;

    $finish;

end

//==========================================================
// Monitor
//==========================================================

initial begin

$monitor(
"Time=%0t | WE=%b | rd=%0d | WData=%0d | rs1=%0d | RData1=%0d | rs2=%0d | RData2=%0d",
    $time,
    reg_write,
    rd,
    write_data,
    rs1,
    read_data1,
    rs2,
    read_data2
);

end

endmodule