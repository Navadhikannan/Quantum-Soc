`timescale 1ns/1ps

module immediate_generator_tb;

parameter XLEN = 32;

//==========================================================
// Inputs
//==========================================================

reg [31:0] instruction;

//==========================================================
// Outputs
//==========================================================

wire [XLEN-1:0] immediate;

//==========================================================
// DUT
//==========================================================

immediate_generator #(
    .XLEN(XLEN)
) dut (

    .instruction(instruction),
    .immediate(immediate)

);

//==========================================================
// Test Sequence
//==========================================================

initial begin

    $dumpfile("immediate_generator.vcd");
    $dumpvars(0, immediate_generator_tb);

    //------------------------------------------------------
    // I-Type : ADDI x5, x6, 10
    //------------------------------------------------------

    instruction = 32'b000000001010_00110_000_00101_0010011;
    #10;

    //------------------------------------------------------
    // I-Type : LW x5, 8(x6)
    //------------------------------------------------------

    instruction = 32'b000000001000_00110_010_00101_0000011;
    #10;

    //------------------------------------------------------
    // S-Type : SW x7, 8(x6)
    //------------------------------------------------------

    instruction = 32'b0000000_00111_00110_010_01000_0100011;
    #10;

    //------------------------------------------------------
    // B-Type : BEQ x6, x7, 16
    //------------------------------------------------------

    instruction = 32'b0000000_00111_00110_000_01000_1100011;
    #10;

    //------------------------------------------------------
    // U-Type : LUI x5, 0x12345
    //------------------------------------------------------

    instruction = 32'h123452B7;
    #10;

    //------------------------------------------------------
    // U-Type : AUIPC x5, 0xABCDE
    //------------------------------------------------------

    instruction = 32'hABCDE297;
    #10;

    //------------------------------------------------------
    // J-Type : JAL x5, 32
    //------------------------------------------------------

    instruction = 32'b00000010000000000000_00101_1101111;
    #10;

    $finish;

end

//==========================================================
// Monitor
//==========================================================

initial begin

$monitor(
"Time=%0t | Instruction=%h | Immediate=%0d (0x%h)",
    $time,
    instruction,
    immediate,
    immediate
);

end

endmodule